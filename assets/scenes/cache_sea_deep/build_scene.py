def build_outer():
    selected=[]
    for r in range(-6,H+6):
        for c in range(-6,W+6):
            if 0<=c<W and 0<=r<H:continue
            if math.hypot(c-14,r-29)<3.2:continue
            ring=max(-c,c-W+1,-r,r-H+1)
            if hash32(c,r)<.35+ring*.06:continue
            selected.append((c,r,9+hash32(r,c)*(6+ring*2.5)))
    occupied={(c,r) for c,r,_ in selected}
    for c,r,ht in selected:
        g=Geo()
        for label,dx,dy,angle in DIRS:
            if (c+dx,r+dy) in occupied:continue
            f=Geo();f.front(0,ht/2,4,ht,-1.98,'M_Rack_Body')
            for j in range(int(ht/2.3)):
                f.front(0,j*2.3+.2,3.72,.045,-1.992,'M_Rack_LED_Channel')
                for x in (-1.25,0,1.25):f.front(x,j*2.3+1.1,.055,1.7,-1.990,'M_Rack_Shadow')
            g.append(f,Matrix.Rotation(angle,4,'Z'))
        g.face([(-2,-2,ht),(2,-2,ht),(2,2,ht),(-2,2,ht)],'M_Rack_Body')
        o=obj_mesh(f'Outer_c{c}_r{r}',g.mesh(f'Outer_{c}_{r}'),COLS['Outer'],cell(c,r),OUTER_ROOT)
        o['cell_c']=c;o['cell_r']=r;o['target_height']=ht;o['role']='outer'
    return len(selected)

