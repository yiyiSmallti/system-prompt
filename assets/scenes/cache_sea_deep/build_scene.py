def source_data():
    text = (ROOT/'game/Assets/SystemPrompt/Scripts/Dungeon/DungeonData.cs').read_text()
    text = text[text.index('["cache_sea_deep"]'):]
    rows = re.findall(r'^\s*"([#.=%A-Za-z0-9]+)",\s*$', text[text.index('Map ='):text.index('Zones')], re.M)
    assert len(rows)==25 and all(len(row)==29 for row in rows)
    zones=[]
    pattern=r'Name = "([^"]+)", Tag = "([^"]+)", Cells = new RectInt\((\d+), (\d+), (\d+), (\d+)\), Style = ZoneStyle\.(\w+)'
    for m in re.finditer(pattern,text):
        name,tag,x,y,w,h,style=m.groups()
        zones.append(dict(name=name,tag=tag,rect=list(map(int,(x,y,w,h))),style=style))
    assert len(zones)==5
    return rows,zones

ROWS,ZONES=source_data()
W,H=29,25

def mark(c,r):
    return ROWS[r][c] if 0<=c<W and 0<=r<H else None

def zone(c,r):
    for z in ZONES:
        x,y,w,h=z['rect']
        if x<=c<x+w and y<=r<y+h:return z['style']
    return 'Channel'

def cell(c,r):
    return Vector((4*c+2,4*(H-1-r)+2,0))

def hash32(c,r):
    # Same single-precision stages as the verified shallow scene and C# Hash.
    a=np.float32(np.float32(c)*np.float32(127.1)+np.float32(r)*np.float32(311.7))
    n=np.float32(np.sin(a))*np.float32(43758.5453)
    return float(np.float32(n-np.floor(n)))

def height(c,r):
    _,_,lo,hi=ZONE_INFO[zone(c,r)]
    h=hash32(c,r)
    return hi+2+h*4 if c in (0,W-1) or r in (0,H-1) else lo+h*(hi-lo)

def islands():
    seen=set();result=set()
    for r in range(H):
        for c in range(W):
            if mark(c,r)!='#' or (c,r) in seen:continue
            group=[];queue=[(c,r)];seen.add((c,r))
            while queue:
                x,y=queue.pop();group.append((x,y))
                for p in ((x+1,y),(x-1,y),(x,y+1),(x,y-1)):
                    if mark(*p)=='#' and p not in seen:seen.add(p);queue.append(p)
            if not any(x in (0,W-1) or y in (0,H-1) for x,y in group):result.update(group)
    return result

