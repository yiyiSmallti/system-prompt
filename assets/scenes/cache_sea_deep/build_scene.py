def damage(c,r,ht,group,col):
    g=Geo()
    for label,dx,dy,angle in DIRS:
        if mark(c+dx,r+dy)=='#':continue
        f=Geo();points=[]
        for j in range(9):
            z=.3+j*(ht-.65)/8
            x=-.45+.19*math.sin(j*2.3+c)+(.20 if j>4 else 0)
            points.append((x,-1.940,z))
        f.tube(points,.045,'M_Emit_Crack',5)
        for j in (2,5):
            x,y,z=points[j];f.tube([(x,y,z),(x+.42,y,z+.35),(x+.64,y,z+.27)],.027,'M_Emit_Crack',4)
        g.append(f,Matrix.Rotation(angle,4,'Z'))
    # Broken cables bend inward over the roof, never down into the adjacent walk cell.
    for i in range(3):
        x=-1.25+i*.88
        g.tube([(x,.2,ht-.8),(x+.12,.35,ht-.12),(x+.42,.45,ht-.20)],.045,'M_Rack_Shadow',5)
        g.cyl((x+.42,.45,ht-.25),.075,.10,'M_Emit_Crack',6)
    if g.f:tag(obj_mesh(f'Rift_c{c:02d}_r{r:02d}_Damage',g.mesh(f'RiftDamage_{c}_{r}'),col,parent=group),c,r,'wall')

def build_rack(c,r,col):
    style=zone(c,r);ht=height(c,r)
    prefix='ServerRow' if (c,r) in ISLANDS and style=='Servers' else 'Rack'
    group=tag(empty(f'{prefix}_c{c:02d}_r{r:02d}',col,cell(c,r),MAIN),c,r,'wall')
    group['target_height']=ht;group['style']=style
    exposed=0
    for label,dx,dy,angle in DIRS:
        if (c,r) in ((12,1),(16,1)):continue
        if mark(c+dx,r+dy)=='#':
            neighbour_height=height(c+dx,r+dy)
            if neighbour_height<ht-.01:
                # Only the band exposed above a shorter neighbour needs a skin.
                # It closes the skyline without modelling hidden internal walls.
                g=Geo();band=ht-neighbour_height
                body='M_White_Body' if style=='WhiteHall' else 'M_Rack_Body'
                trim='M_White_Trim' if style=='WhiteHall' else 'M_Rack_Trim'
                g.front(0,neighbour_height+band/2,4,band,-1.995,body)
                for x in (-1.92,1.92):g.front(x,neighbour_height+band/2,.065,band,-1.997,trim)
                g.front(0,ht-.04,3.72,.035,-1.998,'M_Rack_LED_'+style)
                o=obj_mesh(f'{prefix}_c{c:02d}_r{r:02d}_{label}_Step',g.mesh(f'Step_{c}_{r}_{label}'),col,parent=group)
                o.rotation_euler.z=angle;tag(o,c,r,'wall')
            continue
        exposed+=1
        if prefix=='ServerRow' and label in ('W','E'):
            o=obj_mesh(f'{prefix}_c{c:02d}_r{r:02d}_{label}_LabelSurface',row_end(ht,style),col,parent=group)
            o.rotation_euler.z=angle;tag(o,c,r,'row_end');o['face']=label
            continue
        for layer in range(math.ceil(ht/2.3)):
            remain=min(2.3,ht-layer*2.3)
            variant=int(hash32(c*5+layer,r*7+ord(label))*5.99)
            o=obj_mesh(f'{prefix}_c{c:02d}_r{r:02d}_{label}_L{layer:02d}',facade(style,variant,remain),col,(0,0,layer*2.3),group)
            o.rotation_euler.z=angle;tag(o,c,r,'wall');o['face']=label
        if hash32(c*11+ord(label),r*19)<.19:
            # Copied wall-foot clutter translated 10cm inward.
            g=foot_clutter_geo();g.transform(Matrix.Translation((0,.10,0)))
            for i,m in enumerate(g.materials):
                if m=='M_Rack_LED_Canyon':g.materials[i]='M_Rack_LED_'+style
            o=obj_mesh(f'WallFoot_c{c:02d}_r{r:02d}_{label}',g.mesh(f'Foot_{style}_{c}_{r}_{label}'),col,parent=group)
            o.rotation_euler.z=angle;tag(o,c,r,'wall')
    tag(obj_mesh(f'{prefix}_c{c:02d}_r{r:02d}_Top',roof(style),col,(0,0,ht),group),c,r,'wall')
    if exposed:
        tag(obj_mesh(f'{prefix}_c{c:02d}_r{r:02d}_Fan',FAN,col,(.65,-.55,ht-.10),group),c,r,'wall')
    if style=='Rift' and exposed:damage(c,r,ht,group,col)
    return exposed

