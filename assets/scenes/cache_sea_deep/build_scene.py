    for i in range(6):
        x=-1.05+(i%3)*1.02;y=-.88+(i//3)*1.55;h=.18+(i%3)*.16
        g.box((x,y,h/2),(.75,.91,h),'M_File_Sheet',rot=(i-2)*.11)
